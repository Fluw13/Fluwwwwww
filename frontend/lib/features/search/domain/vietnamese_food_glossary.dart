final Map<String, String> _englishByCanonical = {
  for (final MapEntry(:key, :value) in vietnameseFoodGlossary.entries) canonicalVietnamese(key): value,
};

/// Folded forms shared by entries with different English ("mè" and "me" both fold to "me") are left out: typed
/// without marks they could be either.
final Map<String, String> _englishByFolded = () {
  final byFolded = <String, Set<String>>{};
  for (final MapEntry(:key, :value) in vietnameseFoodGlossary.entries) {
    byFolded.putIfAbsent(foldVietnamese(key), () => {}).add(value);
  }
  return {
    for (final MapEntry(:key, :value) in byFolded.entries)
      if (value.length == 1) key: value.single,
  };
}();

final Set<String> _canonicalDescriptors = {for (final word in _descriptorWords) canonicalVietnamese(word)};

final Set<String> _foldedDescriptors = {for (final word in _descriptorWords) foldVietnamese(word)};

// The folded maps are looked up with the canonical text, which keeps its marks, so they only ever match words typed
// without any: "ca chua" is "cà chua", but "của" is never "cua".
String? _englishFor(String canonicalPhrase) =>
    _englishByCanonical[canonicalPhrase] ?? _englishByFolded[canonicalPhrase];

bool _isDescriptor(String canonicalWord) =>
    _canonicalDescriptors.contains(canonicalWord) || _foldedDescriptors.contains(canonicalWord);

/// English words for USDA when [query] names one known food, alone or with words that describe it: "cà chua",
/// "ca chua", "ức gà luộc" → "chicken breast". The longest known phrase is tried first. Null for anything else,
/// including dishes ("phở bò") whose parts are known foods.
String? englishSearchTermFor(String query) {
  final words = canonicalVietnamese(query).split(' ').where((word) => word.isNotEmpty).toList();
  for (var length = words.length; length > 0; length--) {
    for (var start = 0; start + length <= words.length; start++) {
      final english = _englishFor(words.sublist(start, start + length).join(' '));
      final others = [...words.take(start), ...words.skip(start + length)];
      if (english != null && others.every(_isDescriptor)) {
        return english;
      }
    }
  }
  return null;
}
